#!/usr/bin/env bash
# Package the raw build artifacts into the release asset names used on
# github.com: tic80-v<shortver>-<platform>.<ext>. The itch.io jobs unpack an
# asset like these and push what is inside it (stage-itch.sh), the packages
# into a channel of their own.
#
# Every artifact is a flat directory named after the workflow job (e.g.
# "tic80-windows") holding the raw binaries. This script turns each into the
# final downloadable asset and writes them into <out>.
#
# Usage: package.sh <artifacts-dir> <out-dir> <version> <shortver>
#   version   full "1.2.0"
#   shortver  "1.2" (first two segments; the file-name version)

set -euo pipefail

ART="${1:?artifacts dir}"
OUT="${2:?out dir}"
VER="${3:?version}"
SHORT="${4:?shortver}"

# Resolve to absolute paths up front: zip_flat changes into each artifact
# dir, so a relative $OUT would resolve there and miss.
mkdir -p "$OUT"
ART="$(cd "$ART" && pwd)"
OUT="$(cd "$OUT" && pwd)"

# zip_flat <src-dir> <out.zip> — archive the *contents* of src-dir (binaries
# at the zip root, not nested under the job name).
zip_flat() {
    local src="$1" dst="$2"
    (cd "$src" && zip -q -r -X "$dst" .)
}

# make_deb <src-dir> <out.deb> <arch> — a proper .deb with desktop integration
# (the builder itself lives in make-deb.sh, which the PRO linux job shares).
make_deb() {
    bash bin/release/make-deb.sh "$1" "$2" "$3" "$VER"
}

# --- Windows (the static build is a single .exe) ---
[ -d "$ART/tic80-windows" ] && zip_flat "$ART/tic80-windows" "$OUT/tic80-v$SHORT-win.zip"

# --- Linux ---
if [ -d "$ART/tic80-linux-gcc12" ]; then
    zip_flat "$ART/tic80-linux-gcc12" "$OUT/tic80-v$SHORT-linux.zip"
    make_deb "$ART/tic80-linux-gcc12" "$OUT/tic80-v$SHORT-linux.deb" amd64
fi
if [ -d "$ART/tic80-linux-arm64-gcc12" ]; then
    zip_flat "$ART/tic80-linux-arm64-gcc12" "$OUT/tic80-v$SHORT-linux-arm64.zip"
    make_deb "$ART/tic80-linux-arm64-gcc12" "$OUT/tic80-v$SHORT-linux-arm64.deb" arm64
fi

# --- macOS (binaries + dylibs; the .dmg is built separately on macOS) ---
[ -d "$ART/tic80-macos-arm64" ] && zip_flat "$ART/tic80-macos-arm64" "$OUT/tic80-v$SHORT-mac-arm64.zip"
[ -d "$ART/tic80-macos" ]        && zip_flat "$ART/tic80-macos" "$OUT/tic80-v$SHORT-mac.zip"

# --- Android (rename the apk) ---
[ -f "$ART/tic80-android/tic80.apk" ] && cp "$ART/tic80-android/tic80.apk" "$OUT/tic80-v$SHORT-android.apk"

# --- Consoles ---
[ -f "$ART/tic80-nintendo-3ds/tic80.3dsx" ] && zip_flat "$ART/tic80-nintendo-3ds" "$OUT/tic80-v$SHORT-3ds.zip"
[ -f "$ART/tic80-nintendo-switch/tic80.nro" ] && zip_flat "$ART/tic80-nintendo-switch" "$OUT/tic80-v$SHORT-switch.zip"

# --- Web: only the universal build (tic80.js + tic80.wasm + index.html).
# The per-language wasm variants stay out of the release zip; they are
# shipped to /export as web export stubs by the deploy script.
if [ -d "$ART/tic80-html" ]; then
    tmp="$OUT/.html"
    rm -rf "$tmp"
    mkdir -p "$tmp"
    cp "$ART/tic80-html/tic80.js" "$tmp/" 2>/dev/null || true
    cp "$ART/tic80-html/tic80.wasm" "$tmp/" 2>/dev/null || true
    [ -f "$ART/tic80-html/index.html" ] && cp "$ART/tic80-html/index.html" "$tmp/"
    zip_flat "$tmp" "$OUT/tic80-v$SHORT-html.zip"
    rm -rf "$tmp"
fi

# --- learn.md — the /learn documentation, generated by `export help` ---
[ -f "$ART/tic80-learn/learn.md" ] && cp "$ART/tic80-learn/learn.md" "$OUT/tic80-v$SHORT-learn.md"

# --- export stubs bundle for the server. Not a user download;
# deploy-client.sh pulls it and unpacks into export/<shortver>/. The client
# asks for /export/<shortver>/<command> for a free export, and for
# /export/<shortver>/<command><lang> in PRO alone mode (console.c:2191), so
# every system needs its universal stub plus one stub per language — each
# carries only that runtime, about a third of the universal size.
#
# A missing piece fails the packaging. The linuxarm stub was lost for a
# whole release because this loop looked for "$ART/tic80-linux-arm64-export"
# while the workflow uploads "tic80-linux-arm64-gcc12-export", and the miss
# was a silent `[ -f ] &&`.
STUB_LANGS="lua ruby js moon yue fennel scheme squirrel wren wasm janet python"

if [ -d "$ART" ]; then
    tmp="$OUT/.stubs"
    rm -rf "$tmp"
    mkdir -p "$tmp"
    missing=0
    for spec in windows:win:tic80.exe linux-gcc12:linux:tic80 linux-arm64-gcc12:linuxarm:tic80 macos:macintel:tic80 macos-arm64:mac:tic80; do
        art="${spec%%:*}"; rest="${spec#*:}"; dst="${rest%%:*}"; file="${rest#*:}"
        src="$ART/tic80-$art-export/$file"
        if [ -f "$src" ]; then
            cp "$src" "$tmp/$dst"
        else
            echo "export stub missing: $src" >&2
            missing=1
        fi
        for lang in $STUB_LANGS; do
            lsrc="$ART/tic80-$art-export-langs/tic80$lang"
            [ -f "$lsrc" ] || lsrc="$lsrc.exe"
            if [ -f "$lsrc" ]; then
                cp "$lsrc" "$tmp/$dst$lang"
            else
                echo "export stub missing: $ART/tic80-$art-export-langs/tic80$lang[.exe]" >&2
                missing=1
            fi
        done
    done

    # html: the universal web build as a zip named "html", and one zip per
    # language. The html job already builds tic80<lang>.js/.wasm, so htmllua
    # is those two files plus index.html — with the loader named tic80.js,
    # which is what index.html loads.
    if [ -f "$OUT/tic80-v$SHORT-html.zip" ]; then
        cp "$OUT/tic80-v$SHORT-html.zip" "$tmp/html"
    else
        echo "export stub missing: $OUT/tic80-v$SHORT-html.zip" >&2
        missing=1
    fi
    for lang in $STUB_LANGS; do
        hdir="$ART/tic80-html"
        if [ -f "$hdir/tic80$lang.js" ] && [ -f "$hdir/tic80$lang.wasm" ] && [ -f "$hdir/index.html" ]; then
            htmp="$OUT/.html-$lang"
            rm -rf "$htmp"
            mkdir -p "$htmp"
            cp "$hdir/index.html" "$htmp/"
            cp "$hdir/tic80$lang.js" "$htmp/tic80.js"
            cp "$hdir/tic80$lang.wasm" "$htmp/"
            # zip appends .zip to a name that lacks it; the client asks for
            # /export/<ver>/<system><lang> with no extension (console.c:2191)
            (cd "$htmp" && zip -q -r -X "$tmp/html$lang.zip" .)
            mv "$tmp/html$lang.zip" "$tmp/html$lang"
            rm -rf "$htmp"
        else
            echo "export stub missing: $hdir/{index.html,tic80$lang.js,tic80$lang.wasm}" >&2
            missing=1
        fi
    done

    if [ "$missing" != 0 ]; then
        echo "export stubs incomplete — packaging stopped (see the lines above)" >&2
        exit 1
    fi
    (cd "$tmp" && tar czf "$OUT/tic80-v$SHORT-stubs.tar.gz" .)
    rm -rf "$tmp"
fi

echo "packaged $(ls -1 "$OUT" | wc -l | tr -d ' ') assets into $OUT"
ls -lh "$OUT"
