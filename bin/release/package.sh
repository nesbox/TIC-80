#!/usr/bin/env bash
# Package the raw build artifacts into the release asset names used on
# github.com: tic80-v<shortver>-<platform>.<ext>. The itch.io jobs unpack an
# asset like these and push what is inside it (stage-itch.sh), the packages
# into a channel of their own.
#
# Every artifact is a flat directory named after the workflow job (e.g.
# "tic80-windows") holding the raw binaries. This script turns each into the
# final downloadable asset and writes them into <out>.
#
# Usage: package.sh <artifacts-dir> <out-dir> <version> <shortver>
#   version   full "1.2.0"
#   shortver  "1.2" (first two segments; the file-name version)

set -euo pipefail

ART="${1:?artifacts dir}"
OUT="${2:?out dir}"
VER="${3:?version}"
SHORT="${4:?shortver}"

# Resolve to absolute paths up front: zip_flat changes into each artifact
# dir, so a relative $OUT would resolve there and miss.
mkdir -p "$OUT"
ART="$(cd "$ART" && pwd)"
OUT="$(cd "$OUT" && pwd)"

# zip_flat <src-dir> <out.zip> — archive the *contents* of src-dir (binaries
# at the zip root, not nested under the job name).
zip_flat() {
    local src="$1" dst="$2"
    (cd "$src" && zip -q -r -X "$dst" .)
}

# make_deb <src-dir> <out.deb> <arch> — a proper .deb with desktop integration
# (the builder itself lives in make-deb.sh, which the PRO linux job shares).
make_deb() {
    bash bin/release/make-deb.sh "$1" "$2" "$3" "$VER"
}

# Every asset below is part of the release, and a missing artifact is a
# packaging failure, not a smaller release: the checks are loud and collected
# (the run reports all of them, not the first) the way the export-stub loop
# below does — the linuxarm stub was lost for a whole release because its check
# was a silent `[ -f ] &&`.
missing=0

pack_dir() { # pack_dir <src-dir> <out.zip>
    if [ -d "$1" ]; then
        zip_flat "$1" "$2"
    else
        echo "missing artifact: $1" >&2
        missing=1
    fi
}

pack_deb() { # pack_deb <src-dir> <out.deb> <arch>
    if [ -d "$1" ]; then
        make_deb "$1" "$2" "$3"
    else
        echo "missing artifact: $1" >&2
        missing=1
    fi
}

pack_file() { # pack_file <src> <out>
    if [ -f "$1" ]; then
        cp "$1" "$2"
    else
        echo "missing artifact: $1" >&2
        missing=1
    fi
}

# --- Windows (the static build is a single .exe) ---
pack_dir "$ART/tic80-windows" "$OUT/tic80-v$SHORT-win.zip"

# --- Linux ---
pack_dir "$ART/tic80-linux-gcc12" "$OUT/tic80-v$SHORT-linux.zip"
pack_deb "$ART/tic80-linux-gcc12" "$OUT/tic80-v$SHORT-linux.deb" amd64
pack_dir "$ART/tic80-linux-arm64-gcc12" "$OUT/tic80-v$SHORT-linux-arm64.zip"
pack_deb "$ART/tic80-linux-arm64-gcc12" "$OUT/tic80-v$SHORT-linux-arm64.deb" arm64

# --- macOS (binaries + dylibs; the .dmg is built separately on macOS) ---
pack_dir "$ART/tic80-macos-arm64" "$OUT/tic80-v$SHORT-mac-arm64.zip"
pack_dir "$ART/tic80-macos" "$OUT/tic80-v$SHORT-mac.zip"

# --- Android (rename the apk) ---
pack_file "$ART/tic80-android/tic80.apk" "$OUT/tic80-v$SHORT-android.apk"

# --- Consoles ---
if [ -f "$ART/tic80-nintendo-3ds/tic80.3dsx" ]; then
    zip_flat "$ART/tic80-nintendo-3ds" "$OUT/tic80-v$SHORT-3ds.zip"
else
    echo "missing artifact: $ART/tic80-nintendo-3ds/tic80.3dsx" >&2
    missing=1
fi
if [ -f "$ART/tic80-nintendo-switch/tic80.nro" ]; then
    zip_flat "$ART/tic80-nintendo-switch" "$OUT/tic80-v$SHORT-switch.zip"
else
    echo "missing artifact: $ART/tic80-nintendo-switch/tic80.nro" >&2
    missing=1
fi

# --- Web: only the universal build (tic80.js + tic80.wasm + index.html).
# The per-language wasm variants stay out of the release zip; they are
# shipped to /export as web export stubs by the deploy script.
tmp="$OUT/.html"
rm -rf "$tmp"
mkdir -p "$tmp"
pack_file "$ART/tic80-html/tic80.js" "$tmp/"
pack_file "$ART/tic80-html/tic80.wasm" "$tmp/"
pack_file "$ART/tic80-html/index.html" "$tmp/"
zip_flat "$tmp" "$OUT/tic80-v$SHORT-html.zip"
rm -rf "$tmp"

# --- learn.md — the /learn documentation, generated by `export help` ---
pack_file "$ART/tic80-learn/learn.md" "$OUT/tic80-v$SHORT-learn.md"

# --- export stubs bundle for the server. Not a user download;
# deploy-client.sh pulls it and unpacks into export/<tag>/ — the release tag,
# v1.2.0 — on the box. The client
# asks for /export/<shortver>/<command> for a free export, and for
# /export/<shortver>/<command><lang> in PRO alone mode (console.c exportGame), so
# every system needs its universal stub plus one stub per language — each
# carries only that runtime, about a third of the universal size.
#
# A missing piece fails the packaging. The linuxarm stub was lost for a
# whole release because this loop looked for "$ART/tic80-linux-arm64-export"
# while the workflow uploads "tic80-linux-arm64-gcc12-export", and the miss
# was a silent `[ -f ] &&`.
# Keep in sync with the loops in .github/workflows/build.yml and with
# scriptLanguages in the server's internal/httpapi/export.go: a language
# added to the engine but missed here degrades to a universal-stub download
# (a bigger binary, not an error), so nothing will tell you.
STUB_LANGS="lua ruby js moon yue fennel scheme squirrel wren wasm janet python miniscript forth"

# A per-language stub is a game, not an IDE: the PRO alone export hands the
# cartridge to someone who should only be able to play it. Every job builds
# these with -DBUILD_EDITORS=OFF, and a flag that stops taking effect looks
# exactly like one that took — so check the one thing that says it did: a
# menu label only the editors carry. A universal stub is the other way round:
# it keeps its editors — a free export hands out the player, as it did in
# 1.1, and `alone` is the mode that strips the IDE — so it is checked for the
# marker rather than for its absence. That second check is what would catch a
# free build quietly losing the editors (the Android build did exactly that
# in #2889) before every free export ships without an IDE.
EDITOR_MARKER="SPRITE EDITOR"

no_editors() { # <file> <name in the bundle>
    if grep -qa "$EDITOR_MARKER" "$1"; then
        echo "export stub carries the editors: $2 ($1) — BUILD_EDITORS=OFF did not take" >&2
        smissing=1
    fi
}

has_editors() { # <file> <name in the bundle>
    if ! grep -qa "$EDITOR_MARKER" "$1"; then
        echo "universal export stub lost its editors: $2 ($1) — a free build was made with BUILD_EDITORS=OFF" >&2
        smissing=1
    fi
}

# the site's players are the other way round from the stubs and the same way as
# the universal one: editors kept. Its own flag, `pmissing`, so that a player
# that lost them is not reported as a missing native asset.
player_has_editors() { # <file> <language>
    if ! grep -qa "$EDITOR_MARKER" "$1"; then
        echo "player lost its editors: $2 ($1) — BUILD_EDITORS=ON did not take" >&2
        pmissing=1
    fi
}

if [ -d "$ART" ]; then
    tmp="$OUT/.stubs"
    rm -rf "$tmp"
    mkdir -p "$tmp"
    # its own flag, like the players bundle below: `missing` may be set by a
    # native asset above, and a section that stops the run on someone else's
    # finding is what hides the rest of them
    smissing=0
    for spec in windows:win:tic80.exe linux-gcc12:linux:tic80 linux-arm64-gcc12:linuxarm:tic80 macos:macintel:tic80 macos-arm64:mac:tic80; do
        art="${spec%%:*}"; rest="${spec#*:}"; dst="${rest%%:*}"; file="${rest#*:}"
        src="$ART/tic80-$art-export/$file"
        if [ -f "$src" ]; then
            cp "$src" "$tmp/$dst"
            has_editors "$tmp/$dst" "$dst"
        else
            echo "export stub missing: $src" >&2
            smissing=1
        fi
        for lang in $STUB_LANGS; do
            lsrc="$ART/tic80-$art-export-langs/tic80$lang"
            [ -f "$lsrc" ] || lsrc="$lsrc.exe"
            if [ -f "$lsrc" ]; then
                cp "$lsrc" "$tmp/$dst$lang"
                no_editors "$tmp/$dst$lang" "$dst$lang"
            else
                echo "export stub missing: $ART/tic80-$art-export-langs/tic80$lang[.exe]" >&2
                smissing=1
            fi
        done
    done

    # html: a zip named "html" holding the loader and its wasm, and one zip
    # per language. No page inside — the client fetches index.html from the
    # site at export time, rewrites its title and its arguments marker, and
    # adds it to the zip with the cartridge. That keeps one page in the tree
    # instead of a copy drifting from the player's.
    # A language zip's loader is that language's tic80<lang>.js renamed to
    # tic80.js, because the page loads tic80.js; it asks for
    # tic80<lang>.wasm, which the zip carries under that name.
    hdir="$ART/tic80-html"
    html_stub() { # <name> <loader js> <wasm>
        local name="$1" loader="$2" wasm="$3"
        local stage="$OUT/.html-$name"
        rm -rf "$stage"
        mkdir -p "$stage"
        cp "$loader" "$stage/tic80.js"
        cp "$wasm" "$stage/"
        # zip appends .zip to a name that lacks it; the client asks for
        # /export/<tag>/<system><lang> with no extension (console.c exportGame)
        zip_flat "$stage" "$tmp/$name.zip"
        mv "$tmp/$name.zip" "$tmp/$name"
        rm -rf "$stage"
    }
    if [ -f "$hdir/tic80.js" ] && [ -f "$hdir/tic80.wasm" ]; then
        html_stub html "$hdir/tic80.js" "$hdir/tic80.wasm"
        has_editors "$hdir/tic80.wasm" "html"
    else
        echo "export stub missing: $hdir/{tic80.js,tic80.wasm}" >&2
        smissing=1
    fi
    # one zip per language too: a PRO alone export asks for html<moon>, and
    # without it every one of those falls back to the universal stub (nine
    # megabytes of wasm where two would do) or 404s on a plain host
    for lang in $STUB_LANGS; do
        if [ -f "$hdir/tic80$lang.js" ] && [ -f "$hdir/tic80$lang.wasm" ]; then
            html_stub "html$lang" "$hdir/tic80$lang.js" "$hdir/tic80$lang.wasm"
            no_editors "$hdir/tic80$lang.wasm" "html$lang"
        else
            echo "export stub missing: $hdir/tic80$lang.js|.wasm" >&2
            smissing=1
        fi
    done
    if [ "$smissing" != 0 ]; then
        # nothing half-written and no stale bundle from an earlier run: a
        # caller that ignores the exit code must not find last time's tarball.
        # The run is not stopped here — the players bundle below still has its
        # own checks to report, and the final check fails the packaging.
        missing=1
        rm -rf "$tmp"
        rm -f "$OUT/tic80-v$SHORT-stubs.tar.gz"
        echo "export stubs incomplete (see the lines above)" >&2
    else
        (cd "$tmp" && tar czf "$OUT/tic80-v$SHORT-stubs.tar.gz" .)
        rm -rf "$tmp"
    fi
fi

# --- the site's per-language players, for the server's game pages. Not a user
# download either: deploy-client.sh pulls this and unpacks it into
# js/<tag>/<lang>/ on the box, so a page loads the player of its cartridge's
# language instead of the universal one. They are *not* the export stubs above:
# a stub is built with -DBUILD_EDITORS=OFF (a PRO alone export must not open the
# IDE on ESC), while a game page keeps the editors and is the same build the
# universal player is, one language's runtimes lighter — 543,650 bytes over the
# wire for lua against 2,258,666 (docs/per-language-players.md, server repo).
# The pair is a directory per language with the loader already renamed to the
# tic80.js a page asks for, so a deploy copies it as it is.
#
# A missing piece fails the packaging: a release shipped without this bundle
# leaves every game page on the universal player, which is a silent
# nine-megabyte regression rather than an error. The language list is the stub
# one — both are the engine's languages, and a language added to one loop and
# missed here would be a page that never gets its player.
#
# Collects like the stubs bundle above and lets the final check fail the run:
# every section reports its own findings in one pass, which is the rule the
# header states. Its own flag, because `missing` may be set by a native asset
# above and blaming this section for that would send the reader to the wrong
# loop.
if [ -d "$ART" ]; then
    tmp="$OUT/.players"
    rm -rf "$tmp"
    mkdir -p "$tmp"
    pmissing=0
    for lang in $STUB_LANGS; do
        src="$ART/tic80-html-players/$lang"
        if [ -f "$src/tic80.js" ] && [ -f "$src/tic80$lang.wasm" ]; then
            mkdir -p "$tmp/$lang"
            cp "$src/tic80.js" "$tmp/$lang/"
            cp "$src/tic80$lang.wasm" "$tmp/$lang/"
            player_has_editors "$tmp/$lang/tic80$lang.wasm" "$lang"
        else
            echo "player missing: $ART/tic80-html-players/$lang/{tic80.js,tic80$lang.wasm}" >&2
            pmissing=1
        fi
    done
    if [ "$pmissing" != 0 ]; then
        missing=1
        rm -rf "$tmp"
        rm -f "$OUT/tic80-v$SHORT-players.tar.gz"
        echo "the per-language players are incomplete (see the lines above)" >&2
    else
        (cd "$tmp" && tar czf "$OUT/tic80-v$SHORT-players.tar.gz" .)
        rm -rf "$tmp"
    fi
fi

if [ "$missing" != 0 ]; then
    echo "packaging incomplete — the artifacts listed above are missing" >&2
    exit 1
fi

echo "packaged $(ls -1 "$OUT" | wc -l | tr -d ' ') assets into $OUT"
ls -lh "$OUT"
